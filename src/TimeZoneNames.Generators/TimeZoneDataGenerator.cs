using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace TimeZoneNames.Generators;

/// <summary>
/// Compiles data.json into a TimeZoneData.Load() method, so the data needs no decompression or parsing at runtime.
/// </summary>
[Generator]
public class TimeZoneDataGenerator : IIncrementalGenerator
{
    private const string IgnoreCase = "global::System.StringComparer.OrdinalIgnoreCase";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var source = context.AdditionalTextsProvider
            .Where(file => Path.GetFileName(file.Path) == "data.json")
            .Select((file, ct) => Generate(file.GetText(ct)!.ToString()));

        context.RegisterSourceOutput(source, (spc, code) => spc.AddSource("TimeZoneData.g.cs", SourceText.From(code, Encoding.UTF8)));
    }

    private static string Generate(string json)
    {
        using var reader = new JsonTextReader(new StringReader(json)) { DateParseHandling = DateParseHandling.None };
        var data = JObject.Load(reader);
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("namespace TimeZoneNames;");
        sb.AppendLine();
        sb.AppendLine("internal partial class TimeZoneData");
        sb.AppendLine("{");
        sb.AppendLine("    public static TimeZoneData Load() => new()");
        sb.AppendLine("    {");

        foreach (var name in new[] { "TzdbZoneCountries", "CldrZoneCountries" })
        {
            AppendDictionary(sb, name, (JObject)data[name]!, IgnoreCase, v => $"new string[] {{ {string.Join(", ", v.Select(x => Literal(x)))} }}");
        }

        foreach (var name in new[] { "CldrMetazones", "CldrPrimaryZones", "CldrAliases" })
        {
            AppendDictionary(sb, name, (JObject)data[name]!, IgnoreCase, Literal);
        }

        // One method per language keeps each generated method small enough for the JIT.
        var languages = ((JObject)data["CldrLanguageData"]!).Properties().ToList();
        AppendDictionary(sb, "CldrLanguageData", languages, IgnoreCase, (p, i) => $"Language{i}()");

        sb.AppendLine("        SelectionZones = new()");
        sb.AppendLine("        {");
        foreach (var zone in (JArray)data["SelectionZones"]!)
        {
            var threshold = DateTime.Parse((string)zone["ThresholdUtc"]!, CultureInfo.InvariantCulture, DateTimeStyles.RoundtripKind);
            sb.AppendLine($"            new() {{ Id = {Literal(zone["Id"]!)}, ThresholdUtc = new global::System.DateTime({threshold.Ticks}L, global::System.DateTimeKind.{threshold.Kind}) }},");
        }
        sb.AppendLine("        },");

        var displayNames = ((JObject)data["DisplayNames"]!).Properties().ToList();
        AppendDictionary(sb, "DisplayNames", displayNames, IgnoreCase, (p, i) => $"DisplayNames{i}()");

        sb.AppendLine("    };");

        for (var i = 0; i < languages.Count; i++)
        {
            var language = (JObject)languages[i].Value;
            sb.AppendLine();
            sb.AppendLine($"    private static CldrLanguageData Language{i}() => new()");
            sb.AppendLine("    {");
            if (language["Formats"] is JObject formats)
            {
                sb.AppendLine($"        Formats = {Values(formats)},");
            }
            if (language["FallbackFormat"] is { Type: JTokenType.String } fallbackFormat)
            {
                sb.AppendLine($"        FallbackFormat = {Literal(fallbackFormat)},");
            }
            AppendDictionary(sb, "ShortNames", (JObject)language["ShortNames"]!, IgnoreCase, v => Values((JObject)v));
            AppendDictionary(sb, "LongNames", (JObject)language["LongNames"]!, IgnoreCase, v => Values((JObject)v));
            AppendDictionary(sb, "CountryNames", (JObject)language["CountryNames"]!, IgnoreCase, Literal);
            AppendDictionary(sb, "CityNames", (JObject)language["CityNames"]!, IgnoreCase, Literal);
            sb.AppendLine("    };");
        }

        // The inner display name dictionaries keep the default comparer, matching what JSON deserialization produced.
        for (var i = 0; i < displayNames.Count; i++)
        {
            sb.AppendLine();
            sb.AppendLine($"    private static global::System.Collections.Generic.Dictionary<string, string> DisplayNames{i}() => new()");
            sb.AppendLine("    {");
            foreach (var p in ((JObject)displayNames[i].Value).Properties())
            {
                sb.AppendLine($"        {{ {Literal(p.Name)}, {Literal(p.Value)} }},");
            }
            sb.AppendLine("    };");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void AppendDictionary(StringBuilder sb, string name, JObject obj, string comparer, Func<JToken, string> value) =>
        AppendDictionary(sb, name, obj.Properties().ToList(), comparer, (p, _) => value(p.Value));

    private static void AppendDictionary(StringBuilder sb, string name, List<JProperty> entries, string comparer, Func<JProperty, int, string> value)
    {
        sb.AppendLine($"        {name} = new({comparer})");
        sb.AppendLine("        {");
        for (var i = 0; i < entries.Count; i++)
        {
            sb.AppendLine($"            {{ {Literal(entries[i].Name)}, {value(entries[i], i)} }},");
        }
        sb.AppendLine("        },");
    }

    private static string Values(JObject values)
    {
        var assignments = new[] { "Generic", "Standard", "Daylight" }
            .Where(name => values[name] is { Type: JTokenType.String })
            .Select(name => $"{name} = {Literal(values[name]!)}");
        return $"new() {{ {string.Join(", ", assignments)} }}";
    }

    private static string Literal(JToken token) => Literal((string)token!);

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}
